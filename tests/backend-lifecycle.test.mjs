import assert from 'node:assert/strict';
import { once } from 'node:events';
import WebSocket from 'ws';
import { test } from 'node:test';
import { createServer } from 'node:http';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { withCookie } from './helpers/host-access.mjs';

process.env.TIGHT_USE_HTTP = 'true';
const { startBackend } = await import('../build/backend.js');

test('backend can recover a failed bind and stop repeatedly without leaking its writer', { timeout: 10000 }, async t => {
    const directory = await mkdtemp(path.join(tmpdir(), 'tight-lifecycle-'));
    const occupied = createServer();
    let backend;
    const fetch = (url, options) => globalThis.fetch(url, withCookie(`tight-session=${backend.hostToken}`, options));
    let socket;
    t.after(async () => {
        socket?.terminate();
        await backend?.stop();
        if (occupied.listening) await new Promise(resolve => occupied.close(resolve));
        await rm(directory, { recursive: true, force: true });
    });
    await new Promise(resolve => occupied.listen(0, '127.0.0.1', resolve));
    const address = occupied.address();
    if (!address || typeof address === 'string') throw new Error('Expected TCP address');
    await assert.rejects(startBackend({ host: '127.0.0.1', port: address.port, dataDirectory: directory }), { code: 'EADDRINUSE' });
    backend = await startBackend({ host: '127.0.0.1', port: 0, dataDirectory: directory });
    const response = await fetch(`${backend.origin}/api/game/create`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: '{}' });
    assert.equal(response.status, 200);
    const id = await response.json();
    const exported = await (await fetch(`${backend.origin}/api/game/export?gameId=${id}`)).json();
    await fetch(`${backend.origin}/api/game/delete`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ id }) });
    const oldOrigin = backend.origin;
    await Promise.all([backend.stop(), backend.stop()]);
    await assert.rejects(fetch(oldOrigin, { signal: AbortSignal.timeout(1000) }));
    backend = await startBackend({ host: '127.0.0.1', port: 0, dataDirectory: directory });
    const imported = await fetch(`${backend.origin}/api/game/import`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(exported) });
    assert.equal(imported.status, 200);
    socket = new WebSocket(`${backend.origin.replace('http:', 'ws:')}/socket?gameId=${id}`, { headers: { cookie: `tight-session=${backend.hostToken}` } });
    await once(socket, 'message', { signal: AbortSignal.timeout(2000) });
    const changed = once(socket, 'message', { signal: AbortSignal.timeout(2000) });
    await fetch(`${backend.origin}/api/game/restart`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ id }) });
    const [raw] = await changed;
    const event = JSON.parse(raw.toString());
    assert.equal(event.data.game.deleted, undefined, 'old pending deletion must not cross a server restart');
    assert.equal(event.data.game.created.id, id);
});
